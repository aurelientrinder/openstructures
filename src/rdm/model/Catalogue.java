  /** The rows of a rolled catalogue, or null. */
  static double[][] rolled(Section.Kind k) {
    return switch (k) {
      case IPE -> IPE;
      case HEA -> HEA;
      case HEB -> HEB;
      case UPN -> UPN;
      default -> null;
    };
  }

  /** The row of this designation (the 200 when there is none). */
  static double[] row(Section.Kind k, double designation) {
    double[][] rows = rolled(k);
    for (double[] r : rows) if (r[0] == designation) return r;
    for (double[] r : rows) if (r[0] == 200) return r;
    return rows[0];
  }

  /**
   * {A (mm²), I (mm⁴)} of a rectangular hollow section h × b × t bending about the axis parallel to b, by
   * EN 10210-2 Annex A.3: the rectangles less the corners outside the radius 1.5 t, plus those inside the radius t.
   */
  static double[] rectangularHollow(double h, double b, double t) {
    double ro = 1.5 * t, ri = t;
    double a = 2 * t * (b + h - 2 * t) - (4 - Math.PI) * (ro * ro - ri * ri);
    double i = (b * h * h * h - (b - 2 * t) * Math.pow(h - 2 * t, 3)) / 12 - 4 * corner(ro, h / 2) + 4 * corner(ri, (h - 2 * t) / 2);
    return new double[] {a, i};
  }

  /** The second moment, about the axis, of the part of a square r × r outside its quarter circle, at y from it. */
  private static double corner(double r, double y) {
    double a = (1 - Math.PI / 4) * r * r;
    double d = y - (10 - 3 * Math.PI) / (12 - 3 * Math.PI) * r;
    double i = (1.0 / 3 - Math.PI / 16 - 1 / (3 * (12 - 3 * Math.PI))) * Math.pow(r, 4);
    return i + a * d * d;
  }
